import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const DRAFTS_DIR = path.join('prompts', 'drafts');
const OUTPUT_FILE = path.join('src', 'shared', 'generated', 'compare-drafts.ts');

function toStem(filename) {
  return filename.replace(/\.md$/i, '');
}

function compareNames(left, right) {
  return left.localeCompare(right, 'en', { sensitivity: 'base', numeric: true });
}

export async function listCompareDraftFiles(rootDir) {
  const draftsDir = path.join(rootDir, DRAFTS_DIR);
  let entries;
  try {
    entries = await readdir(draftsDir, { withFileTypes: true });
  } catch (error) {
    if (error && typeof error === 'object' && 'code' in error && error.code === 'ENOENT') {
      return [];
    }
    throw error;
  }

  return entries
    .filter((entry) => entry.isFile() && entry.name.toLowerCase().endsWith('.md'))
    .map((entry) => ({
      filename: entry.name,
      label: toStem(entry.name),
      id: toStem(entry.name),
      absolutePath: path.join(draftsDir, entry.name),
    }))
    .sort((left, right) => compareNames(left.filename, right.filename));
}

export async function buildCompareDraftRegistrySource(rootDir) {
  const drafts = await listCompareDraftFiles(rootDir);
  const cards = await Promise.all(
    drafts.map(async (draft) => ({
      id: draft.id,
      label: draft.label,
      content: await readFile(draft.absolutePath, 'utf8'),
    })),
  );

  return `import type { CompareDraftCard } from '../types.js';

// Auto-generated by build/compare-drafts-registry.mjs
export const COMPARE_DRAFT_CARDS: CompareDraftCard[] = ${JSON.stringify(cards, null, 2)};
`;
}

export async function writeCompareDraftRegistry(rootDir) {
  const outputFile = path.join(rootDir, OUTPUT_FILE);
  const source = await buildCompareDraftRegistrySource(rootDir);
  await mkdir(path.dirname(outputFile), { recursive: true });
  await writeFile(outputFile, source, 'utf8');
  return outputFile;
}

export async function ensureCompareDraftRegistry(rootDir) {
  await writeCompareDraftRegistry(rootDir);
}
